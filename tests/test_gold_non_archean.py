def test_gold_compare_is_deterministic_across_two_processes():
    def run():
        proc = subprocess.run(
            [sys.executable, str(REPO_ROOT / "scripts" / "gold_compare.py"), "--json"],
            capture_output=True, text=True, encoding="utf-8", errors="replace",
            timeout=120,
        )
        assert proc.returncode == 0
        return proc.stdout

    a, b = run(), run()
    assert a == b


