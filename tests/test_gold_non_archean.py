"""Tests for tests/data/gold_non_archean.json and scripts/gold_compare.py.

Three groups, matching Phase 8 of this step:

  integrity      the gold file is internally well-formed and its evidence is
                 real — every citation actually occurs on the page it names.
  independence   the gold labels were not generated by route.py, typeRdd, or
                 scripts/analyze_routing.py — checked structurally, not by
                 trusting the file's own prose claim.
  comparison     scripts/gold_compare.py's output is deterministic and its
                 categorisation is internally consistent with the gold file.

Nothing here asserts that route.py is "right" or "wrong" — see
DISCOVERY.md 8.8 for that discussion. These tests only protect the gold
file's integrity and the comparison's reproducibility.
"""

