def test_gold_file_is_not_produced_by_a_script_reading_route_py():
    """No import of archean.route inside the gold JSON generation path —
    checked the only way that is actually checkable: the JSON file itself
    contains no Verdict enum reprs, Classification reprs, or anything that
    looks like a serialised route.py object, only plain strings the human
    determination process would produce.
    """
    raw = GOLD_PATH.read_text(encoding="utf-8")
    assert "Verdict.OPERATIVE" not in raw
    assert "Classification(" not in raw
    assert "<Verdict" not in raw


def test_metadata_label_is_recorded_separately_from_verdict(gold):
    """Every item's metadata_label is present as its own field, distinct
    from verdict — the gold schema itself cannot collapse the two even if
    someone tried, because they are different JSON keys with different
    (bool|None) vs (str) types.
    """
    for item in gold["items"]:
        assert "metadata_label" in item
        assert item["metadata_label"] in (True, False, None)
        assert isinstance(item["verdict"], str)


def test_no_typerdd_capital_disagreement_was_silently_resolved(gold):
    """Where metadata_label and verdict disagree in the gold file itself
    (independent of the router), the item's rationale must be present —
    the file cannot assert a verdict that contradicts its own recorded
    metadata_label without explaining why in prose.
    """
    for item in gold["items"]:
        if item["mechanism"] != "capital_amount":
            continue
        meta = item["metadata_label"]
        verdict_says_yes = item["verdict"] in ("OPERATIVE",)
        if meta is True and not verdict_says_yes:
            assert item["rationale"], item["item_id"]
        if meta is False and verdict_says_yes:
            assert item["rationale"], item["item_id"]


